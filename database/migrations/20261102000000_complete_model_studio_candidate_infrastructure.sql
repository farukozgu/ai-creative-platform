-- Forward-only completion of the partially installed Model Studio foundation.
-- Prepared for review only. Apply as one migration transaction after review.
BEGIN;
SET LOCAL statement_timeout = '60s';
SET LOCAL lock_timeout = '5s';

-- Stabilize the foundation/data inspected below until this transaction ends.
LOCK TABLE public.model_profiles,public.model_identity_versions,
  public.model_reference_assets,public.model_identity_version_references
  IN SHARE ROW EXCLUSIVE MODE;

-- Fail closed before schema changes. The production catalog preflight supplied
-- these baseline facts; this gate rechecks relevant structure/data at apply time.
DO $preflight$
DECLARE
  t record;
  c record;
  expected_count integer;
BEGIN
  IF current_user <> 'postgres' THEN
    RAISE EXCEPTION 'Model Studio repair must run as postgres; current_user=%', current_user;
  END IF;
  IF current_setting('server_version_num')::integer < 140000 THEN
    RAISE EXCEPTION 'Model Studio repair requires PostgreSQL 14 or newer';
  END IF;

  IF to_regclass('public.model_profiles') IS NULL
    OR to_regclass('public.model_identity_versions') IS NULL
    OR to_regclass('public.model_reference_assets') IS NULL
    OR to_regclass('public.model_identity_version_references') IS NULL THEN
    RAISE EXCEPTION 'Required Model Studio foundation table is missing';
  END IF;
  IF to_regclass('public.model_candidate_jobs') IS NOT NULL
    OR to_regclass('public.model_candidates') IS NOT NULL THEN
    RAISE EXCEPTION 'Candidate table already exists; inspect partial install instead of replaying repair';
  END IF;
  IF to_regprocedure('public.approve_model_candidate(uuid,uuid)') IS NOT NULL
    OR to_regprocedure('public.claim_queued_model_candidate_jobs(integer,integer)') IS NOT NULL
    OR to_regprocedure('public.renew_model_candidate_lease(uuid,uuid,bigint,integer)') IS NOT NULL THEN
    RAISE EXCEPTION 'Candidate RPC already exists; inspect partial install instead of replacing it';
  END IF;
  IF to_regnamespace('klay_model_security') IS NOT NULL THEN
    RAISE EXCEPTION 'klay_model_security already exists; inspect name collision before repair';
  END IF;
  IF to_regprocedure('public.enforce_model_candidate_ownership()') IS NOT NULL
    OR to_regprocedure('public.enforce_model_version_reference_ownership()') IS NOT NULL
    OR to_regprocedure('public.set_model_candidate_job_timestamps()') IS NOT NULL THEN
    RAISE EXCEPTION 'Candidate integrity helper function already exists; inspect partial install';
  END IF;
  IF EXISTS (SELECT 1 FROM pg_attribute WHERE attrelid='public.model_profiles'::regclass
      AND attname IN ('current_identity_version_id','approved_candidate_id')
      AND attnum>0 AND NOT attisdropped) THEN
    RAISE EXCEPTION 'A profile pointer column already exists; inspect partial install';
  END IF;

  -- Verify all foundation columns needed by the candidate contracts.
  FOR c IN SELECT * FROM (VALUES
    ('model_profiles','id','uuid',true), ('model_profiles','user_id','uuid',true),
    ('model_profiles','status','text',true), ('model_profiles','appearance','jsonb',true),
    ('model_identity_versions','id','uuid',true), ('model_identity_versions','model_id','uuid',true),
    ('model_identity_versions','user_id','uuid',true), ('model_identity_versions','version_number','integer',true),
    ('model_identity_versions','appearance','jsonb',true),
    ('model_reference_assets','id','uuid',true), ('model_reference_assets','model_id','uuid',true),
    ('model_reference_assets','user_id','uuid',true), ('model_reference_assets','bucket_id','text',true),
    ('model_reference_assets','object_path','text',true), ('model_reference_assets','source','text',true),
    ('model_identity_version_references','identity_version_id','uuid',true),
    ('model_identity_version_references','reference_asset_id','uuid',true),
    ('model_identity_version_references','view','text',true)
  ) AS x(table_name,column_name,data_type,not_null)
  LOOP
    IF NOT EXISTS (
      SELECT 1 FROM pg_attribute a
      WHERE a.attrelid=to_regclass('public.'||c.table_name)
        AND a.attname=c.column_name AND a.attnum>0 AND NOT a.attisdropped
        AND format_type(a.atttypid,a.atttypmod)=c.data_type
        AND a.attnotnull=c.not_null
    ) THEN RAISE EXCEPTION 'Foundation column contract mismatch: %.%',c.table_name,c.column_name; END IF;
  END LOOP;

  -- These named constraints are generated by the original foundation migration.
  -- Check the actual definitions, not merely the presence of their names.
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.model_profiles'::regclass
      AND conname='model_profiles_pkey' AND contype='p'
      AND pg_get_constraintdef(oid)='PRIMARY KEY (id)')
    OR NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.model_profiles'::regclass
      AND conname='model_profiles_user_id_fkey' AND contype='f'
      AND confrelid='auth.users'::regclass AND confdeltype='c')
    OR NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.model_profiles'::regclass
      AND conname='model_profiles_appearance_check' AND contype='c'
      AND pg_get_constraintdef(oid) LIKE '%jsonb_typeof(appearance)%object%')
    OR NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.model_identity_versions'::regclass
      AND conname='model_identity_versions_model_id_fkey' AND contype='f'
      AND confrelid='public.model_profiles'::regclass AND confdeltype='c')
    OR NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.model_identity_versions'::regclass
      AND conname='model_identity_versions_user_id_fkey' AND contype='f'
      AND confrelid='auth.users'::regclass AND confdeltype='c')
    OR NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.model_identity_versions'::regclass
      AND conname='model_identity_versions_pkey' AND contype='p'
      AND pg_get_constraintdef(oid)='PRIMARY KEY (id)')
    OR NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.model_reference_assets'::regclass
      AND conname='model_reference_assets_model_id_fkey' AND contype='f'
      AND confrelid='public.model_profiles'::regclass AND confdeltype='c')
    OR NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.model_reference_assets'::regclass
      AND conname='model_reference_assets_pkey' AND contype='p'
      AND pg_get_constraintdef(oid)='PRIMARY KEY (id)')
    OR NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.model_identity_version_references'::regclass
      AND conname='model_identity_version_references_identity_version_id_fkey' AND contype='f'
      AND confrelid='public.model_identity_versions'::regclass AND confdeltype='c')
    OR NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.model_identity_version_references'::regclass
      AND conname='model_identity_version_references_reference_asset_id_fkey' AND contype='f'
      AND confrelid='public.model_reference_assets'::regclass AND confdeltype='r') THEN
    RAISE EXCEPTION 'Model Studio foundation constraint contract mismatch';
  END IF;

  -- F-07 requires the known SECURITY INVOKER guard owned by this migration role,
  -- attached exactly once as BEFORE UPDATE FOR EACH ROW.
  IF NOT EXISTS (SELECT 1 FROM pg_proc p WHERE p.oid=to_regprocedure('public.enforce_model_profile_transition()')
      AND pg_get_userbyid(p.proowner)=current_user AND NOT p.prosecdef
      AND p.prolang=(SELECT oid FROM pg_language WHERE lanname='plpgsql')
      AND p.proconfig=ARRAY['search_path=""']) THEN
    RAISE EXCEPTION 'Profile transition guard owner/security/search_path differs from verified foundation';
  END IF;
  SELECT count(*) INTO expected_count FROM pg_trigger g
  WHERE g.tgrelid='public.model_profiles'::regclass AND NOT g.tgisinternal
    AND g.tgname='model_profiles_enforce_transition'
    AND g.tgfoid=to_regprocedure('public.enforce_model_profile_transition()')
    AND g.tgtype=19 AND g.tgenabled IN ('O','A') AND g.tgnargs=0;
  IF expected_count<>1 OR (SELECT count(*) FROM pg_trigger g
      WHERE g.tgfoid=to_regprocedure('public.enforce_model_profile_transition()') AND NOT g.tgisinternal)<>1 THEN
    RAISE EXCEPTION 'Profile transition trigger attachment differs from verified foundation';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgrelid='public.model_profiles'::regclass
      AND tgname='model_profiles_set_timestamps' AND tgtype=23 AND tgenabled IN ('O','A')
      AND tgfoid=to_regprocedure('public.set_model_profile_timestamps()'))
    OR NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgrelid='public.model_identity_versions'::regclass
      AND tgname='model_identity_versions_immutable' AND tgtype=27 AND tgenabled IN ('O','A')
      AND tgfoid=to_regprocedure('public.prevent_model_version_mutation()')) THEN
    RAISE EXCEPTION 'Foundational timestamp or immutable-version trigger differs from contract';
  END IF;
  IF (SELECT count(*) FROM pg_trigger WHERE tgrelid='public.model_profiles'::regclass AND NOT tgisinternal)<>2
    OR (SELECT count(*) FROM pg_trigger WHERE tgrelid='public.model_identity_versions'::regclass AND NOT tgisinternal)<>2
    OR (SELECT count(*) FROM pg_trigger WHERE tgrelid='public.model_reference_assets'::regclass AND NOT tgisinternal)<>0
    OR (SELECT count(*) FROM pg_trigger WHERE tgrelid='public.model_identity_version_references'::regclass AND NOT tgisinternal)<>0 THEN
    RAISE EXCEPTION 'Unexpected custom trigger on a foundational Model Studio table';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_proc WHERE oid=to_regprocedure('public.prevent_model_version_mutation()')
      AND pg_get_userbyid(proowner)=current_user AND NOT prosecdef
      AND proconfig=ARRAY['search_path=""']) THEN
    RAISE EXCEPTION 'Immutable-version trigger function owner/security differs from contract';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_proc WHERE oid=to_regprocedure('public.set_model_profile_timestamps()')
      AND pg_get_userbyid(proowner)=current_user AND NOT prosecdef
      AND proconfig=ARRAY['search_path=""'])
    OR NOT EXISTS (SELECT 1 FROM pg_proc WHERE oid=to_regprocedure('public.enforce_model_version_ownership()')
      AND pg_get_userbyid(proowner)=current_user AND NOT prosecdef
      AND proconfig=ARRAY['search_path=""']) THEN
    RAISE EXCEPTION 'Foundational trigger function ownership/security differs from contract';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgrelid='public.model_identity_versions'::regclass
      AND tgname='model_identity_versions_enforce_ownership' AND tgtype=7 AND tgenabled IN ('O','A')
      AND tgfoid=to_regprocedure('public.enforce_model_version_ownership()')) THEN
    RAISE EXCEPTION 'Identity-version ownership trigger differs from foundation';
  END IF;

  IF (SELECT count(*) FROM pg_constraint WHERE conrelid='public.model_profiles'::regclass)<>6
    OR (SELECT count(*) FROM pg_constraint WHERE conrelid='public.model_identity_versions'::regclass)<>6
    OR (SELECT count(*) FROM pg_constraint WHERE conrelid='public.model_reference_assets'::regclass)<>9
    OR (SELECT count(*) FROM pg_constraint WHERE conrelid='public.model_identity_version_references'::regclass)<>5
    OR EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid IN (
      'public.model_profiles'::regclass,'public.model_identity_versions'::regclass,
      'public.model_reference_assets'::regclass,'public.model_identity_version_references'::regclass)
      AND NOT convalidated)
    OR NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.model_profiles'::regclass
      AND conname='model_profiles_name_check' AND contype='c'
      AND pg_get_constraintdef(oid) LIKE '%char_length(name)%1%80%')
    OR NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.model_profiles'::regclass
      AND conname='model_profiles_status_check' AND contype='c'
      AND pg_get_constraintdef(oid) LIKE '%draft%candidate_pending%identity_review_pending%approved%archived%')
    OR NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.model_profiles'::regclass
      AND conname='model_profiles_notes_check' AND contype='c'
      AND lower(pg_get_constraintdef(oid)) LIKE '%char_length(coalesce(notes%' AND pg_get_constraintdef(oid) LIKE '%600%')
    OR NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.model_identity_versions'::regclass
      AND conname='model_identity_versions_version_number_check'
      AND pg_get_constraintdef(oid) LIKE '%version_number > 0%')
    OR NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.model_identity_versions'::regclass
      AND conname='model_identity_versions_model_id_version_number_key' AND contype='u'
      AND pg_get_constraintdef(oid)='UNIQUE (model_id, version_number)')
    OR NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.model_identity_versions'::regclass
      AND conname='model_identity_versions_appearance_check' AND contype='c'
      AND pg_get_constraintdef(oid) LIKE '%jsonb_typeof(appearance)%object%')
    OR NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.model_reference_assets'::regclass
      AND conname='model_reference_assets_byte_size_check'
      AND pg_get_constraintdef(oid) LIKE '%byte_size > 0%20971520%')
    OR NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.model_reference_assets'::regclass
      AND conname='model_reference_assets_user_id_fkey' AND contype='f'
      AND confrelid='auth.users'::regclass AND confdeltype='c')
    OR NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.model_reference_assets'::regclass
      AND conname='model_reference_assets_bucket_id_check' AND contype='c'
      AND pg_get_constraintdef(oid) LIKE '%bucket_id%model-reference-assets%')
    OR NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.model_reference_assets'::regclass
      AND conname='model_reference_assets_source_check' AND contype='c'
      AND pg_get_constraintdef(oid) LIKE '%candidate_generated%')
    OR NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.model_reference_assets'::regclass
      AND conname='model_reference_assets_mime_type_check' AND contype='c'
      AND pg_get_constraintdef(oid) LIKE '%image/jpeg%image/png%image/webp%')
    OR NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.model_reference_assets'::regclass
      AND conname='model_reference_assets_check' AND contype='c'
      AND pg_get_constraintdef(oid) LIKE '%split_part%user_id%model_id%')
    OR NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.model_reference_assets'::regclass
      AND conname='model_reference_assets_bucket_id_object_path_key' AND contype='u'
      AND pg_get_constraintdef(oid)='UNIQUE (bucket_id, object_path)')
    OR NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.model_identity_version_references'::regclass
      AND conname='model_identity_version_references_pkey'
      AND contype='p' AND pg_get_constraintdef(oid)='PRIMARY KEY (identity_version_id, reference_asset_id)')
    OR NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.model_identity_version_references'::regclass
      AND conname='model_identity_version_references_identity_version_id_view_key' AND contype='u'
      AND pg_get_constraintdef(oid)='UNIQUE (identity_version_id, view)')
    OR NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.model_identity_version_references'::regclass
      AND conname='model_identity_version_references_view_check'
      AND pg_get_constraintdef(oid) LIKE '%front%three_quarter%side%') THEN
    RAISE EXCEPTION 'Model Studio foundational constraint count or definition differs from migration';
  END IF;

  -- Preserve and validate the original owner policies and API grant boundary.
  -- pg_policy.polcmd is the internal code (r=SELECT, a=INSERT, w=UPDATE).
  IF (SELECT count(*) FROM pg_policy WHERE polrelid='public.model_profiles'::regclass)<>3
    OR NOT EXISTS (SELECT 1 FROM pg_policy WHERE polrelid='public.model_profiles'::regclass
      AND polname='Owners select model profiles' AND polcmd='r'
      AND 'authenticated'::regrole=ANY(polroles) AND pg_get_expr(polqual,polrelid) LIKE '%auth.uid()%user_id%')
    OR NOT EXISTS (SELECT 1 FROM pg_policy WHERE polrelid='public.model_profiles'::regclass
      AND polname='Owners insert model profiles' AND polcmd='a'
      AND pg_get_expr(polwithcheck,polrelid) LIKE '%auth.uid()%user_id%draft%')
    OR NOT EXISTS (SELECT 1 FROM pg_policy WHERE polrelid='public.model_profiles'::regclass
      AND polname='Owners update model profiles' AND polcmd='w'
      AND pg_get_expr(polqual,polrelid) LIKE '%auth.uid()%user_id%'
      AND pg_get_expr(polwithcheck,polrelid) LIKE '%auth.uid()%user_id%draft%archived%') THEN
    RAISE EXCEPTION 'model_profiles RLS policy contract differs from foundation';
  END IF;
  IF (SELECT count(*) FROM pg_policy WHERE polrelid='public.model_identity_versions'::regclass)<>1
    OR NOT EXISTS (SELECT 1 FROM pg_policy WHERE polrelid='public.model_identity_versions'::regclass
      AND polname='Owners select model versions' AND polcmd='r'
      AND 'authenticated'::regrole=ANY(polroles) AND pg_get_expr(polqual,polrelid) LIKE '%auth.uid()%user_id%')
    OR (SELECT count(*) FROM pg_policy WHERE polrelid='public.model_reference_assets'::regclass)<>1
    OR NOT EXISTS (SELECT 1 FROM pg_policy WHERE polrelid='public.model_reference_assets'::regclass
      AND polname='Owners select model reference assets' AND polcmd='r'
      AND 'authenticated'::regrole=ANY(polroles) AND pg_get_expr(polqual,polrelid) LIKE '%auth.uid()%user_id%')
    OR (SELECT count(*) FROM pg_policy WHERE polrelid='public.model_identity_version_references'::regclass)<>1
    OR NOT EXISTS (SELECT 1 FROM pg_policy WHERE polrelid='public.model_identity_version_references'::regclass
      AND polname='Owners select model version references' AND polcmd='r'
      AND 'authenticated'::regrole=ANY(polroles) AND pg_get_expr(polqual,polrelid) LIKE '%model_identity_versions%auth.uid()%') THEN
    RAISE EXCEPTION 'Foundation identity/reference RLS policy contract differs from migration';
  END IF;
  IF NOT (SELECT relrowsecurity FROM pg_class WHERE oid='public.model_profiles'::regclass)
    OR NOT (SELECT relrowsecurity FROM pg_class WHERE oid='public.model_identity_versions'::regclass)
    OR NOT (SELECT relrowsecurity FROM pg_class WHERE oid='public.model_reference_assets'::regclass)
    OR NOT (SELECT relrowsecurity FROM pg_class WHERE oid='public.model_identity_version_references'::regclass)
    OR NOT has_table_privilege('authenticated','public.model_profiles','SELECT')
    OR NOT has_table_privilege('authenticated','public.model_profiles','INSERT')
    OR NOT has_table_privilege('authenticated','public.model_profiles','UPDATE')
    OR has_table_privilege('anon','public.model_profiles','SELECT')
    OR has_table_privilege('service_role','public.model_profiles','SELECT')
    OR has_table_privilege('authenticated','public.model_identity_versions','UPDATE')
    OR has_table_privilege('authenticated','public.model_identity_versions','DELETE') THEN
    RAISE EXCEPTION 'Foundation RLS or table-grant boundary differs from verified contract';
  END IF;
  IF NOT has_table_privilege('authenticated','public.model_reference_assets','SELECT')
    OR NOT has_table_privilege('authenticated','public.model_identity_version_references','SELECT')
    OR NOT has_table_privilege('authenticated','public.model_identity_versions','SELECT')
    OR has_table_privilege('anon','public.model_identity_versions','SELECT')
    OR has_table_privilege('anon','public.model_reference_assets','SELECT')
    OR has_table_privilege('anon','public.model_identity_version_references','SELECT')
    OR has_table_privilege('service_role','public.model_identity_versions','SELECT')
    OR has_table_privilege('service_role','public.model_reference_assets','SELECT')
    OR has_table_privilege('service_role','public.model_identity_version_references','SELECT') THEN
    RAISE EXCEPTION 'Foundation authenticated read grants or anon denial differs from migration';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM storage.buckets WHERE id='model-reference-assets' AND NOT public)
    -- pg_policies.cmd is the user-facing command name, unlike pg_policy.polcmd.
    OR NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname='storage' AND tablename='objects'
      AND policyname='Owners read model reference objects' AND cmd='SELECT'
      AND qual LIKE '%model-reference-assets%')
    OR NOT has_table_privilege('service_role','storage.objects','INSERT')
    OR NOT has_table_privilege('service_role','storage.objects','SELECT') THEN
    RAISE EXCEPTION 'Private Model Studio Storage boundary differs from foundation';
  END IF;

  -- No data repair/backfill is attempted. The supplied F-07 checks are repeated
  -- to protect against changes between inspection and application.
  IF EXISTS (SELECT 1 FROM public.model_profiles
      WHERE status NOT IN ('draft','archived','approved'))
    OR EXISTS (SELECT 1 FROM public.model_profiles WHERE status='approved')
    OR EXISTS (SELECT 1 FROM public.model_identity_versions v
      LEFT JOIN public.model_profiles p ON p.id=v.model_id AND p.user_id=v.user_id WHERE p.id IS NULL) THEN
    RAISE EXCEPTION 'Existing Model Studio rows violate F-07 assumptions; no data was changed';
  END IF;

  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname IN ('anon','authenticated','service_role')
      GROUP BY rolname HAVING count(*)<>1)
    OR NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='anon')
    OR NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='authenticated')
    OR NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='service_role') THEN
    RAISE EXCEPTION 'Expected Supabase API roles are missing';
  END IF;
  IF NOT (SELECT rolbypassrls FROM pg_roles WHERE rolname='service_role') THEN
    RAISE EXCEPTION 'service_role must retain Supabase BYPASSRLS for trusted server-side candidate persistence';
  END IF;
END;
$preflight$;

-- Add only the two absent profile pointers; no existing profile is rewritten.
ALTER TABLE public.model_profiles
  ADD COLUMN current_identity_version_id uuid NULL
    CONSTRAINT model_profiles_current_identity_version_id_fkey
    REFERENCES public.model_identity_versions(id) ON DELETE RESTRICT,
  ADD COLUMN approved_candidate_id uuid NULL
    CONSTRAINT model_profiles_approved_candidate_id_key UNIQUE;

CREATE TABLE public.model_candidate_jobs (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  model_id uuid NOT NULL REFERENCES public.model_profiles(id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  idempotency_key uuid NOT NULL,
  status text NOT NULL DEFAULT 'queued' CHECK (status IN ('queued','processing','succeeded','failed','ambiguous')),
  provider text NOT NULL DEFAULT 'openai',
  model text NOT NULL,
  appearance_snapshot jsonb NOT NULL CHECK (jsonb_typeof(appearance_snapshot)='object'),
  provider_metadata jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(provider_metadata)='object'),
  error_code text NULL,
  lease_token uuid NULL,
  lease_expires_at timestamptz NULL,
  lease_version bigint NOT NULL DEFAULT 0,
  provider_submitted_at timestamptz NULL,
  submission_state text NOT NULL DEFAULT 'not_started'
    CHECK (submission_state IN ('not_started','submitting','submitted','ambiguous','persisted')),
  reconciliation_required_at timestamptz NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT model_candidate_jobs_user_model_idempotency_key_key
    UNIQUE (user_id,model_id,idempotency_key)
);
CREATE INDEX model_candidate_jobs_owner_model_idx
  ON public.model_candidate_jobs(user_id,model_id,created_at DESC);
CREATE INDEX model_candidate_jobs_claim_idx
  ON public.model_candidate_jobs(status,created_at) WHERE status='queued';

CREATE TABLE public.model_candidates (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  job_id uuid NOT NULL REFERENCES public.model_candidate_jobs(id) ON DELETE CASCADE,
  model_id uuid NOT NULL REFERENCES public.model_profiles(id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','ready','failed','rejected')),
  appearance_snapshot jsonb NOT NULL CHECK (jsonb_typeof(appearance_snapshot)='object'),
  primary_reference_asset_id uuid NULL REFERENCES public.model_reference_assets(id) ON DELETE RESTRICT,
  created_at timestamptz NOT NULL DEFAULT now(),
  finalized_at timestamptz NULL
);
CREATE INDEX model_candidates_owner_model_idx
  ON public.model_candidates(user_id,model_id,created_at DESC);

ALTER TABLE public.model_candidate_jobs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.model_candidates ENABLE ROW LEVEL SECURITY;
CREATE POLICY "Owners select model candidate jobs" ON public.model_candidate_jobs
  FOR SELECT TO authenticated USING ((SELECT auth.uid())=user_id);
-- Authenticated users may read their jobs/candidates, but cannot enqueue jobs.
-- Queue insertion and state transitions remain server-authorized.
CREATE POLICY "Owners select model candidates" ON public.model_candidates
  FOR SELECT TO authenticated USING ((SELECT auth.uid())=user_id);
REVOKE ALL ON public.model_candidate_jobs,public.model_candidates FROM PUBLIC,anon,authenticated,service_role;
GRANT SELECT ON public.model_candidate_jobs,public.model_candidates TO authenticated;
-- The server-only admin client is the intended writer. These grants support
-- enqueue/result/metadata persistence while browser roles remain read-only.
-- The SECURITY INVOKER ownership triggers also need trusted server SELECTs.
-- No current RPC creates jobs/results or stores reference metadata: claim and
-- renewal only manage leases; approval publishes already-persisted evidence.
GRANT SELECT ON public.model_profiles TO service_role;
GRANT SELECT,INSERT,UPDATE ON public.model_candidate_jobs,public.model_candidates TO service_role;
