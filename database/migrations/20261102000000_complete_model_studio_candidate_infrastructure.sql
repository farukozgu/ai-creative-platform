CREATE FUNCTION public.enforce_model_candidate_ownership()
RETURNS trigger LANGUAGE plpgsql SECURITY INVOKER SET search_path=''
AS $function$
BEGIN
  IF TG_TABLE_SCHEMA<>'public' OR TG_LEVEL<>'ROW' OR TG_WHEN<>'BEFORE'
    OR TG_OP NOT IN ('INSERT','UPDATE') OR TG_NARGS<>0 THEN
    RAISE EXCEPTION 'Unsupported candidate ownership trigger context';
  END IF;
  IF TG_TABLE_NAME='model_candidate_jobs' THEN
    IF NOT EXISTS (SELECT 1 FROM public.model_profiles p
      WHERE p.id=NEW.model_id AND p.user_id=NEW.user_id) THEN
      RAISE EXCEPTION 'Model ownership mismatch';
    END IF;
  ELSIF TG_TABLE_NAME='model_candidates' THEN
    IF NOT EXISTS (SELECT 1 FROM public.model_profiles p
      WHERE p.id=NEW.model_id AND p.user_id=NEW.user_id) THEN
      RAISE EXCEPTION 'Model ownership mismatch';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM public.model_candidate_jobs j
      WHERE j.id=NEW.job_id AND j.model_id=NEW.model_id AND j.user_id=NEW.user_id) THEN
      RAISE EXCEPTION 'Candidate job ownership mismatch';
    END IF;
  ELSE
    RAISE EXCEPTION 'Unsupported candidate ownership trigger table: %.%',TG_TABLE_SCHEMA,TG_TABLE_NAME;
  END IF;
  RETURN NEW;
END;
$function$;
CREATE TRIGGER model_candidate_jobs_owner_guard BEFORE INSERT OR UPDATE ON public.model_candidate_jobs
  FOR EACH ROW EXECUTE FUNCTION public.enforce_model_candidate_ownership();
CREATE TRIGGER model_candidates_owner_guard BEFORE INSERT OR UPDATE ON public.model_candidates
  FOR EACH ROW EXECUTE FUNCTION public.enforce_model_candidate_ownership();

